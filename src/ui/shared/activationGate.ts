/**
 * 「同一个手势只算一次激活」——双击闸（BUG-135 / BUG-136 一族的共用件）。
 *
 * 为什么要有这个文件：浏览器把一次双击派发成**两次 click**。多数控件的第二次激活
 * 是幂等的（写同一个值），所以平时看不出来；但只要第一次激活**卸载 / 移动了**它自己
 * 或它的邻居，第二次就落到别的元素上；或者动作本身是 toggle 语义（开 / 关），两次
 * 就是「开了又关」。两种都表现为用户那句「我点了它，结果不是它」。
 *
 * 判据用**浏览器自己数好的连击计数**（`MouseEvent.detail`），而不是自己记时间戳 /
 * 坐标：一次双击的第 2 下 `detail === 2`（三击是 3…），浏览器只把「同一位置、间隔在
 * 系统双击阈值内」的点击计进去——正好是我们要的那件事，我们不必再维护窗口与坐标。
 * （自己记坐标的写法在 jsdom 里是坏的：合成的 click 坐标恒为 0，会把「后一次真实
 * 点击」误判成同一个手势的第二下。）
 *
 * 程序化派发的 click（`.click()` / 无障碍工具 / 测试）`detail` 是 0，闸自然不生效——
 * 失败方向是「回到旧行为」，不是「吞掉用户的操作」。
 */

/** `click.detail >= 2` = 这是同一手势里的第 2 下（双击 / 三击 / …） */
export function isRepeatClick(detail: number): boolean {
  return detail >= 2
}

/** 关掉浮层后等「第二下」的兜底时长（ms）：等不到就把监听摘掉。只需覆盖双击阈值 */
export const REPEAT_WATCH_MS = 500
