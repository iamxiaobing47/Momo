// Momo 核心类型（contract-momo-storage）的出口：文件是唯一事实源，索引条目仅是
// 视图投影。插件 data.json 只允许存软删登记、视图偏好、设置；禁止存正文/标签/图片。
//
// 三层分工（拆开后仍是同一个模块，靠 `from '../momo/types'` 引用）：
// - prefs.ts    一个偏好长什么样：枚举 / 顺序 / 白名单 / 合法区间 / 默认值
// - entry.ts    整个 data.json 长什么样：条目 / 设置 / 软删登记
// - sanitize.ts 盘上脏数据怎么兜底：逐个字段的 sanitize 与钳制
// - sanitizeKit.ts 上面那些 sanitize 共用的**骨架**（枚举 / 布尔 / 钳制 / 记录表 / 清单）——
//   只放形状，不放任何字段的取值口径，所以**不从本 barrel 导出**：serviceDisk 与 account
//   深引它，界面代码不该看见。
// 界面文案一律走 copy（src/momo/i18n）：这里只留**结构**，展示名 / 说明放字典的
// meta 段（用 Record<枚举, …> 声明，漏一个成员编译不过）。

