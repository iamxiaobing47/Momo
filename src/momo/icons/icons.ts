/**
 * `prefs.icons` 的形状：**稀疏覆写表**——键 = 语义图标名，值 = Lucide 库 id。
 * 表里没有的键 = 用 Momo 原形（PATHS）。存覆写不存"恢复默认"哨兵值：
 * 恢复默认 = 把键从表里删掉，盘上天然干净。
 */
export type IconOverrides = Partial<Record<ConfigurableIconName, string>>

/**
 * 解析一枚语义图标的实际路径：有覆写且库里有那枚 → 库形状；否则 → PATHS 原形。
 *
 * 两道兜底都是防御性的（sanitize 已挡掉脏键脏值，但 pathsOf 也会被设置页 /
 * 测试用非净化输入调用）：覆写值不在库里 → 回落 PATHS，绝不返回空数组
 * （空数组 = 一枚"换了却没形状"的空洞图标，比不换更糟）。
 *
 * 返回值是**模块常量引用**：PATHS[name] / LUCIDE_PATHS[id] 都是稳定对象，
 * 调用方（Icon 的 useUi selector）靠引用相等跳过无关重渲染。
 */
export function iconPaths(name: IconName, icons: IconOverrides | undefined): readonly string[] {
  // leaf 被 sanitize 挡在盘外，这里按 IconName 通查一次只为让类型闭合
  const id = icons ? (icons as Partial<Record<IconName, string>>)[name] : undefined
  if (id !== undefined) {
    const ds = LUCIDE_PATHS[id]
    if (ds) return ds
  }
  return PATHS[name]
}
