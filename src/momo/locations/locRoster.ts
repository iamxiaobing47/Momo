// ---- 索引（模块级一次性构建：模块加载即建 Map，构造是 O(n)，万条库的渲染路径上
// 每次查询只是 Map.has，与旧字典的属性查找同价）----

/**
 * 检索折叠：小写 + 剥拉丁变音符（NFD 分解后去掉 U+0300–036F 的组合记号）——
 * 「krakow」命中「Kraków」、「cancun」命中「Cancún」；ASCII 大小写同理。**不能**
 * 用 `\p{M}` 一把全剥：日文片假名的浊点 / 半浊点（ペ = ベ + U+309A）也是组合
 * 记号，剥了会把「ペナン」折成「ベナン」，与国家别名撞车（浊音在日文里是音节
 * 的一部分，不是装饰）。CJK 经 NFD 原样不变。**只用于比对**，写进 frontmatter
 * 的永远是名册 / 别名表里的原形。
 */
export function foldLocName(s: string): string {
  return s.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')
}

/**
 * 紧写折叠（比 `foldLocName` 再宽一级）：把**分隔符**也抹掉——空白、连字符、
 * 撇号（' 与 ’）、句点、间隔号 ·、下划线。
 *
 * 为什么需要这一级（2026-10-06 用户实测：输入「NewYork」球上不出光点）：名册的
 * 英文名是**分词的**（New York / San Francisco / Ho Chi Minh City / Xi'an /
 * Nuku'alofa），543 城里有 52 个英文名带空格、5 个带撇号、2 个带连字符、1 个带
 * 句点——约 60 座城（11%）。用户手打地名时**连写是常态**（NewYork、SanFrancisco、
 * Xian），而分隔符在「是不是同一座城」这件事上不承载信息，剥掉它们只是不让人为
 * 一条空格赔掉一个光点。压扁后 543×3 个名字**零撞车**（守卫测试盯着），所以这一
 * 级不会引入歧义；万一将来数据撞了，建表时那个键会被标记为歧义键并**整条不登记**
 * （宁可查不到，不可查错城）。
 *
 * 与 `foldLocName` 同口径：**只用于比对**，写进 frontmatter 的永远是名册原形。
 */
export function foldLocNameTight(s: string): string {
  return stripLocSeparators(foldLocName(s))
}

/** 分隔符：抹掉后「new york」与「newyork」同键。字面量里 `-` 放最后免得被当范围 */
const LOC_SEP_RE = /[\s'’.\-·_]/g

/** 折叠形 → 紧写形（入参已折叠时用这个，省一次 NFD） */
function stripLocSeparators(s: string): string {
  return s.replace(LOC_SEP_RE, '')
}

/** 名字 → 城市的精确索引（zh / en / ja 三个名都进同一张表；重名冲突 = 数据错误，
 *  守卫测试 loc-roster.test.mts 盯着「同名必同城」） */
const CITY_BY_NAME: ReadonlyMap<string, LocRosterCity> = buildNameIndex(LOC_ROSTER)

/**
 * 一批「精确键 → 值」的宽比对索引（折叠层 + 紧写层），城市与国家共用一台——
 * 两边的宽容级别必须一致，否则「New York」查得到坐标却查不到归属。
 *
 * - 折叠层：`foldLocName(k) !== k` 的键才登记（CJK 折叠是自身，省一张死表；
 *   折叠层的撞车不处理——折叠是「大小写 / 变音符不敏感」，撞了说明表本身有问题，
 *   由数据守卫测试盯着）；
 * - 紧写层（最后一级兜底：「NewYork」→「New York」）：`t === k || t === foldLocName(k)`
 *   的键不登记（紧写后与精确 / 折叠层同形 = 那两层已经查得到）。撞车处理：同一个
 *   紧写键指向两个**不同**的值 = 歧义，那个键**整条不登记**（`ambiguous` 记住，
 *   后来者也不许再占）——宁可查不到（退化到改前的表现），不可查错。
 */
export function buildFoldedTiers<V>(exact: ReadonlyMap<string, V>): {
  folded: ReadonlyMap<string, V>
  tight: ReadonlyMap<string, V>
} {
  const folded = new Map<string, V>()
  for (const [k, v] of exact) {
    const f = foldLocName(k)
    if (f !== k) folded.set(f, v)
  }
  const tight = new Map<string, V>()
  const ambiguous = new Set<string>()
  for (const [k, v] of exact) {
    const f = foldLocName(k)
    const t = stripLocSeparators(f)
    if (t === k || t === f) continue
    if (ambiguous.has(t)) continue
    const prev = tight.get(t)
    if (prev === undefined) {
      tight.set(t, v)
    } else if (prev !== v) {
      ambiguous.add(t)
      tight.delete(t)
    }
  }
  return { folded, tight }
}

/**
 * 名字 → 值的三级递减查表（**都是查数据的宽容，不是地点身份**）：
 *   ① 精确；② 折叠比对（小写 + 剥变音符）：「tokyo」「krakow」命中正形；
 *   ③ 紧写比对（再剥分隔符）：「NewYork」「SanFrancisco」「Xian」命中正形。
 * 不碰「地点身份按精确串」的存储口径（normalizeLocations 照旧不折叠）。
 */
export function tieredLookup<V>(
  exact: ReadonlyMap<string, V>,
  tiers: { folded: ReadonlyMap<string, V>; tight: ReadonlyMap<string, V> },
  name: string,
): V | null {
  const hit = exact.get(name)
  if (hit !== undefined) return hit
  const folded = HAS_LATIN.test(name) ? foldLocName(name) : name
  const byFolded = tiers.folded.get(folded)
  if (byFolded !== undefined) return byFolded
  // ⚠️ 别在这里加「tight === folded 就早退」的省事判断：查询串自己没有分隔符
  // （「NewYork」「Xian」）时 tight 恒等于 folded，早退会把**正是要修的那一类**
  // 全部挡在门外——分隔符长在名册那一侧，不长在用户打的字上。一次 Map.get 的
  // 代价换正确性，划算。
  return tiers.tight.get(stripLocSeparators(folded)) ?? null
}

const CITY_TIERS = buildFoldedTiers(CITY_BY_NAME)

function buildNameIndex(roster: readonly LocRosterCity[]): ReadonlyMap<string, LocRosterCity> {
  const m = new Map<string, LocRosterCity>()
  for (const city of roster) {
    for (const name of [city.zh, city.en, city.ja]) {
      m.set(name, city)
    }
  }
  return m
}

/** 有拉丁字母才可能有折叠形（CJK 折叠是自身，别为它白付 NFD + 正则的分配） */
const HAS_LATIN = /[A-Za-z]/

export function rosterCityOf(name: string): LocRosterCity | null {
  return tieredLookup(CITY_BY_NAME, CITY_TIERS, name)
}

/** 名册的一处命中：`location` = 选中后写进 frontmatter 的字符串，`city` = 名册记录 */
export interface RosterHit {
  location: string
  city: LocRosterCity
}

/**
 * 名册搜索（地点弹层的建议来源）：query 是任一语言名的**子串**即命中（ASCII
 * 不分大小写、变音符可省、分隔符可省，见 foldLocName / foldLocNameTight），
 * 按「整词精确 → 紧写整词 → 前缀命中 → 子串命中」排序，最多 `limit` 条。
 *
 * 选中后写哪个名（`RosterHit.location`）：query 与某名**整词一致**（折叠后比对，
 * 紧写整词也算）就写那个名——用户写了哪种文字就进哪种（写「東京」进「東京」，写
 * 「krakow」进「Kraków」正形，写「NewYork」进「New York」正形）；只是前缀 / 子串
 * 命中时写当前界面语言的名字（zh 界面搜「Tok」得「东京」，en 界面得「Tokyo」）
 * ——名册是三语的，落笔跟人走。
 *
 * 「紧写整词写正形」是刻意的：名册那一行是三语 + 坐标 + 归属的唯一真源，写正形
 * 才走**精确键**（①级），不依赖任何兜底；用户打的「NewYork」即使没选建议、直接
 * 回车建成自由地点，坐标 / 归属也照样查得到（rosterCityOf 第③级）。
 */
export function rosterMatches(query: string, locale: 'zh' | 'en' | 'ja', limit: number): RosterHit[] {
  const q = query.trim()
  if (q === '') return []
  const ql = foldLocName(q)
  const qt = stripLocSeparators(ql)
  const prefix: RosterHit[] = []
  const infix: RosterHit[] = []
  for (const city of LOC_ROSTER) {
    const names = [city.zh, city.en, city.ja]
    const folded = names.map(foldLocName)
    // 整词命中：写在哪个语言就进哪个语言；立即定格并顶到最前
    const exactAt = folded.indexOf(ql)
    if (exactAt >= 0) {
      prefix.unshift({ location: names[exactAt], city })
      continue
    }
    // 紧写整词命中（「NewYork」/「Xian」/「HoChiMinhCity」）：同样按命中的语言落笔
    const tightAt = qt === '' ? -1 : folded.findIndex((n) => stripLocSeparators(n) === qt)
    if (tightAt >= 0) {
      prefix.unshift({ location: names[tightAt], city })
      continue
    }
    const matchedAt = folded.findIndex((n) => n.startsWith(ql) || n.includes(ql))
    if (matchedAt >= 0) {
      const localeName = locale === 'en' ? city.en : locale === 'ja' ? city.ja : city.zh
      const hit: RosterHit = { location: localeName, city }
      ;(folded[matchedAt].startsWith(ql) ? prefix : infix).push(hit)
      continue
    }
    // 兜到紧写的前缀 / 子串（「newyor」「sanfran」）：落界面语言名
    if (qt === '') continue
    const tightMatchedAt = folded.findIndex((n) => {
      const t = stripLocSeparators(n)
      return t.startsWith(qt) || t.includes(qt)
    })
    if (tightMatchedAt < 0) continue
    const localeName = locale === 'en' ? city.en : locale === 'ja' ? city.ja : city.zh
    const hit: RosterHit = { location: localeName, city }
    const t0 = stripLocSeparators(folded[tightMatchedAt])
    ;(t0.startsWith(qt) ? prefix : infix).push(hit)
  }
  return [...prefix, ...infix].slice(0, limit)
}
