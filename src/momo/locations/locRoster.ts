// 地点名册（F1/F7 的数据底座升级）：**一本三语的世界城市名册**，替代原来分散在
// locCoords.ts（坐标）与 locRegions.ts（归属）里的两份手抄城市表。
//
// 为什么合成一本账：原来「加一个城市」要在坐标表与归属表各记一行，键集靠守卫测试
// 钉死才不漂移；现在每座城市只有**一条记录**（三语名 + 大洲 + 国家 + 坐标），
// 两张查找表都从这本册子**派生**（见那两个文件），键集天然一致，漂移在构造上不可能。
//
// 三语口径（zh / en / ja 都是这张册子的**键**，frontmatter 里写哪种都能查到）：
// - zh：中文标准名（简体，与既有字典逐字一致——老用户盘上的「北京」「纽约」
//   一个都不能失效）；**zh 是一座城市的正名**，弹层选中名册城市时默认写它。
// - en：英文通行 exonym，**纯 ASCII**（慕尼黑写 Munich 不写 München，守卫测试
//   盯着）——ASCII 才能做大小写折叠，「tokyo」也能命中「Tokyo」。
// - 三语名之外的**写法宽容**由检索侧负责（foldLocName / foldLocNameTight）：大小写、
//   变音符、以及**分隔符**（空格 / 连字符 / 撇号 / 句点）都可省——「NewYork」
//   「sanfrancisco」「Xian」都命中各自的正形。宽容只放「查数据」，不放「地点
//   身份」：写进 frontmatter 的永远是名册里的原形。
// - ja：日文通行写法（汉字城市用 shinjitai 汉字：広島、韓国用 韓国；外来语城市
//   用片假名：ニューヨーク、パリ）。
//
// 收录口径（「尽量覆盖全世界」的现实边界）：**各国首都 + 各国主要城市 + 常见
// 旅行目的地**，五百余城（准数 = `LOC_ROSTER.length`，界面文案由它现推，增删城市
// 不必改这里）。不是 GeoNames 全集——本册是**离线内置数据**，每一行
// 都要为体积（main.js）与正确性（坐标手校）负责；小国微型城市、微小岛屿首都没收
// 的，用户可在设置页手填坐标 / 归属（prefs.locCoords / prefs.locRegions，
// 用户值压过内置，见那两个文件的查找函数）。
//
// 既有 299 城的 zh 名与坐标**逐字保留**（v0.9.x 起随插件发货的数据，存量用户的
// frontmatter 与星球锚点都钉在它们上）；英日名是本轮新增的键。
//
// 坐标精度与 locCoords.ts 同口径：两位小数 ≈ 1km 级，星球锚点足够。
// 这些是纯数据与纯函数：不碰文件、不 import obsidian（momo/ 层红线）。
// 城市名与国名是**专有名词数据不是界面文案**（lint-copy 白名单，理由同 locRegions.ts）。

/** 名册城市的大洲取值（标准六块，扣掉没有任何常用地点的南极洲，与归属字典同口径） */
export type LocRosterContinent = '亚洲' | '欧洲' | '非洲' | '北美洲' | '南美洲' | '大洋洲'

/** 名册里的一座城市：三语名 + 归属 + 坐标。`zh` 是正名（既有字典的键） */
export interface LocRosterCity {
  /** 中文名（简体标准名，与既有内置字典逐字一致） */
  zh: string
  /** 英文名（通行 exonym，纯 ASCII） */
  en: string
  /** 日文名（汉字 shinjitai 或片假名） */
  ja: string
  /** 大洲（六块之一） */
  continent: LocRosterContinent
  /** 国家（中文标准名，必须是 BUILTIN_LOC_COUNTRIES 的键——守卫测试盯着） */
  country: string
  /** [纬度, 经度]，两位小数 */
  coord: LatLon
}

/** 行构造器：位置参数太散（大洲 / 国家都是串），写错由守卫测试兜住——
 *  大洲错被各洲包围盒逮住、国家错被「国家必须落在国家表且同洲」逮住 */
function c(
  zh: string,
  en: string,
  ja: string,
  continent: LocRosterContinent,
  country: string,
  lat: number,
  lon: number,
): LocRosterCity {
  return { zh, en, ja, continent, country, coord: [lat, lon] }
}

