/**
 * アクティビティヒートマップ（サイドバーのローリングウィンドウ）+
 * 統計ページのアクティビティカレンダー共用。データも色階調も同じなので文言は1份。
 */
export const heatmap = {
  /** サイドバー区画のタイトル */
  title: 'アクティビティ',
  /**
   * サイドバーのサブタイトル：`直近3か月`。1か月のときは `今月`——ウィンドウが
   * 当月まるごとを敷くので（2026-10-09 ユーザー要望）、「直近1か月」では画面と合わない。
   */
  range: (months: number): string => (months === 1 ? '今月' : `直近${months}か月`),
  /** 統計ページのカードタイトル */
  calendarTitle: 'アクティビティカレンダー',
  prevYear: '前の年',
  nextYear: '次の年',
  /** 色階調の凡例の両端 */
  less: '少',
  more: '多',
  /** 格子のホバー表示：`9月28日 · 3 件`（日付 + その日の件数） */
  tip: (monthDay: string, count: number): string => `${monthDay} · ${count} 件`,
}
